import type { ReportModel } from "./models.ts";
import { ACCENT, INK, MUTED, Writer, dateLong, heading, inr, monthLong, newDoc, safe, table } from "./writer.ts";

const pct = (n: number) => `${Math.round(n * 100)}%`;

/** A printable report for the owner's books or their CA: same numbers as the Reports screen. */
export async function renderReport(m: ReportModel): Promise<Uint8Array> {
  const r = m.report;
  const scope = m.scope;
  const period = `${monthLong(r.from)} – ${monthLong(r.to)}${r.complete ? "" : " (year to date)"}`;
  const t = r.totals;

  const { doc, font, bold } = await newDoc(`Rental income report ${r.label}`);
  const w = new Writer(doc, font, bold);
  w.brand("Rental income report", "", `Prepared ${dateLong(r.today)}`, `${r.label} · ${scope}`);

  w.pair("Owner", m.ownerName || "Owner", { bold: true });
  w.pair("Period", period);
  w.pair("Properties", scope);
  w.rule();

  /* Headline numbers */
  const kpi = (x: number, label: string, value: string, color = INK) => {
    w.page.drawText(safe(label), { x: w.m + x, y: w.y - 9, size: 8.5, font, color: MUTED });
    w.page.drawText(safe(value), { x: w.m + x, y: w.y - 27, size: 15, font: bold, color });
  };
  w.ensure(48);
  const col = w.w / 4;
  kpi(0, "Income", inr(t.income));
  kpi(col, "Expenses", inr(t.expenses));
  kpi(col * 2, "Profit", inr(t.profit), t.profit >= 0 ? ACCENT : INK);
  kpi(col * 3, "Occupancy", pct(t.occupancy));
  w.gap(42);
  w.para(
    `Collected ${inr(t.collected)} of ${inr(t.billed)} billed (${pct(t.collectionRate)}). Income counts confirmed payments by the date received; expenses count approved entries only.`,
    { size: 8.5, color: MUTED, after: 6 },
  );

  heading(w, "Month by month");
  table(
    w,
    ["Month", "Income", "Expenses", "Profit", "Billed", "Let"],
    r.months.map((m) => [monthLong(m.month), m.income, m.expenses, m.profit, m.billed, `${m.occupied} of ${m.units}`]),
    { numWidth: 70, total: ["Total", t.income, t.expenses, t.profit, t.billed, pct(t.occupancy)] },
  );

  if (r.byProperty.length > 1) {
    heading(w, "By property");
    table(
      w,
      ["Property", "Income", "Expenses", "Profit", "Let now"],
      r.byProperty.map((p) => [p.name, p.income, p.expenses, p.profit, `${p.occupied} of ${p.units}`]),
      { numWidth: 78 },
    );
  }

  heading(
    w,
    "Rent received by tenant",
    "Confirmed payments received in this period, and the rent and utilities billed for its months.",
  );
  if (r.byTenant.length) {
    table(
      w,
      ["Tenant · unit", "Billed", "Received"],
      r.byTenant.map((x) => [`${x.tenantName}${x.units ? ` · ${x.units}` : ""}`, x.billed, x.received]),
      {
        numWidth: 90,
        total: ["Total", r.byTenant.reduce((s, x) => s + x.billed, 0), r.byTenant.reduce((s, x) => s + x.received, 0)],
      },
    );
  } else w.para("No rent received in this period.", { size: 9, color: MUTED, after: 8 });

  heading(w, "Expenses by category");
  if (r.categories.length) {
    table(
      w,
      ["Category", "Amount", "Share"],
      r.categories.map((c) => [c.category, c.amount, t.expenses ? pct(c.amount / t.expenses) : "-"]),
      { numWidth: 90, total: ["Total", t.expenses, ""] },
    );
  } else w.para("No approved expenses in this period.", { size: 9, color: MUTED, after: 8 });

  if (r.latePayers.length) {
    heading(w, "Paying late", "Months where rent was fully paid after the due date, or is still unpaid.");
    table(
      w,
      ["Tenant", "Late months", "Avg. days late", "Unpaid"],
      r.latePayers.map((p) => [
        p.tenantName,
        `${p.lateMonths} of ${p.months}`,
        String(p.avgDaysLate),
        p.unpaid ? String(p.unpaid) : "-",
      ]),
      { numWidth: 84 },
    );
  }

  if (r.fy !== null) {
    heading(
      w,
      "Income from house property (estimate)",
      "A starting point for your CA, worked out on rent received. Home-loan interest and any other deductions are not included.",
    );
    w.pair("Rent received", inr(r.tax.rentReceived));
    w.pair("Less: municipal tax paid (expenses marked Tax)", inr(r.tax.municipalTax));
    w.pair("Net annual value", inr(r.tax.netAnnualValue));
    w.pair("Less: standard deduction at 30%", inr(r.tax.standardDeduction));
    w.rule();
    w.pair("Income from house property", inr(r.tax.taxable), { bold: true });
  }

  w.footer(`Generated by pOS from the rent ledger on ${dateLong(r.today)}. Figures in Indian rupees.`);
  return doc.save();
}
