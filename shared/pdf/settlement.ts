import { rgb } from "pdf-lib";
import type { SettlementModel } from "./models.ts";
import { METHOD, MUTED, Writer, dateLong, inr, newDoc } from "./writer.ts";

const KIND: Record<string, string> = {
  damage: "Damage / repairs",
  rent: "Unpaid rent",
  utility: "Unpaid utilities",
  other: "Other",
};

/**
 * A4 move-out and deposit settlement statement. A draft prints with a DRAFT notice (the numbers can still change);
 * a final settlement carries its number (S-0001) and, once paid, the refund details.
 */
export async function renderSettlement(m: SettlementModel): Promise<Uint8Array> {
  const { doc, font, bold } = await newDoc(`Deposit settlement ${m.number || "draft"}`);
  const w = new Writer(doc, font, bold);
  w.brand(
    "Move-out & deposit settlement",
    m.number,
    `Issued ${dateLong(m.issuedOn)}`,
    m.final ? undefined : "Draft · not final",
  );

  if (!m.final) {
    w.text("DRAFT", { size: 18, bold: true, color: rgb(0.85, 0.45, 0.05) });
    w.lineDone(18, 1.3);
    w.para("These figures are a working copy and can still change until the landlord finalises the settlement.", {
      size: 9,
      color: MUTED,
      after: 8,
    });
  }

  w.pair("Tenant", m.tenantName, { bold: true });
  if (m.tenantPhone) w.pair("Mobile", m.tenantPhone);
  w.pair("Property", `${m.unitLabel}, ${m.propertyName}`);
  if (m.address) w.pair("Address", m.address);
  w.pair("Tenancy", `${dateLong(m.startDate)} to ${dateLong(m.moveOutDate)}`);
  w.pair("Move-out date", dateLong(m.moveOutDate));
  w.rule();

  w.text("Deposit", { size: 9, color: MUTED });
  w.lineDone(9, 1.6);
  w.pair("Security deposit held", inr(m.depositHeld));
  if (m.advanceUnused > 0) w.pair("Rent paid for months after move-out", inr(m.advanceUnused));
  w.rule();

  w.text("Deductions", { size: 9, color: MUTED });
  w.lineDone(9, 1.6);
  if (m.deductions.length) {
    for (const d of m.deductions) {
      const label = KIND[d.kind] ?? d.kind;
      w.pair(d.description && d.description !== label ? `${label}: ${d.description}` : label, inr(d.amount));
    }
  } else {
    w.pair("No deductions", inr(0));
  }
  w.pair("Total deductions", inr(m.deductionTotal), { bold: true });
  if (m.outstandingRent > 0 || m.pendingUtilities > 0) {
    w.para(
      `At move-out the ledger showed ${inr(m.outstandingRent)} unpaid rent and ${inr(m.pendingUtilities)} unpaid utility bills.`,
      { size: 8.5, color: MUTED, after: 4 },
    );
  }
  w.rule();

  const owes = m.refundAmount < 0;
  w.text(owes ? "Amount the tenant still owes" : "Refund to the tenant", { size: 9, color: MUTED });
  w.lineDone(9, 1.6);
  w.text(inr(Math.abs(m.refundAmount)), { size: 24, bold: true });
  w.lineDone(24, 1.25);
  w.para(
    owes
      ? "The deductions are more than the deposit held. This is the balance after the whole deposit was adjusted."
      : `Deposit ${inr(m.depositHeld)} - deductions ${inr(m.deductionTotal)}${m.advanceUnused > 0 ? ` + unused advance ${inr(m.advanceUnused)}` : ""}.`,
    { size: 9, color: MUTED, after: 8 },
  );
  if (!owes && m.refundAmount > 0) {
    if (m.refundStatus === "paid") {
      w.pair(
        "Refund paid",
        `${m.refundPaidOn ? dateLong(m.refundPaidOn) : ""}${m.refundMethod ? ` · ${METHOD[m.refundMethod] ?? m.refundMethod}` : ""}${m.refundRef ? ` · Ref ${m.refundRef}` : ""}`,
        { bold: true },
      );
    } else w.pair("Refund status", "Pending");
  }
  if (m.note) w.pair("Note", m.note);
  w.rule();

  w.para(
    m.final
      ? "Both parties agree that this statement settles the security deposit for the tenancy above."
      : "Draft for review.",
    { size: 10, after: 26 },
  );
  w.text(m.ownerName || "Landlord", { bold: true });
  w.text(m.tenantName, { bold: true, x: w.w / 2 + 20 });
  w.lineDone(10);
  w.text(`Landlord${m.ownerPhone ? ` · ${m.ownerPhone}` : ""}${m.ownerPan ? ` · PAN ${m.ownerPan}` : ""}`, {
    size: 8.5,
    color: MUTED,
  });
  w.text("Tenant", { size: 8.5, color: MUTED, x: w.w / 2 + 20 });
  w.lineDone(8.5);
  w.footer("Generated by pOS from the rent ledger. A computer-generated statement.");
  return doc.save();
}
