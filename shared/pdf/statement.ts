import type { StatementModel } from "./models.ts";
import { METHOD, MUTED, Writer, dateLong, heading, inr, monthLong, newDoc, table } from "./writer.ts";

const PERIOD: Record<StatementModel["period"], string> = {
  month: "Monthly rent statement",
  year: "Annual rent statement",
  fy: "Financial-year rent statement",
};

/** "2026-04 to 2026-06" → "Apr 2026 to Jun 2026"; a single month stays one month. */
function monthsLabel(s: string) {
  const [a, b] = s.split(" to ");
  const short = (m: string) => monthLong(m).replace(/^(\w{3})\w*/, "$1");
  return b ? `${short(a)} to ${short(b)}` : short(a);
}

/**
 * A4 rent statement for one tenancy over a month, a year or an April–March financial year. Laid out for an HRA
 * claim: who paid whom for which address, the landlord's PAN, month-wise rent and every payment received.
 */
export async function renderStatement(m: StatementModel): Promise<Uint8Array> {
  const { doc, font, bold } = await newDoc(`Rent statement ${m.periodLabel}`);
  const w = new Writer(doc, font, bold);
  w.brand(PERIOD[m.period], "", `Issued ${dateLong(m.issuedOn)}`, m.periodLabel);

  w.pair("Tenant", m.tenantName, { bold: true });
  if (m.tenantPhone) w.pair("Mobile", m.tenantPhone);
  if (m.tenantPan) w.pair("Tenant PAN", m.tenantPan);
  w.pair("Rented premises", `${m.unitLabel}, ${m.propertyName}`);
  if (m.address) w.pair("Address", m.address);
  w.pair("Landlord", m.ownerName || "Landlord", { bold: true });
  if (m.ownerPhone) w.pair("Landlord mobile", m.ownerPhone);
  w.pair("Landlord PAN", m.ownerPan || "Not provided");
  w.pair("Period", m.from === m.to ? monthLong(m.from) : `${monthLong(m.from)} to ${monthLong(m.to)}`);
  w.rule();

  /* Headline numbers */
  const kpi = (x: number, label: string, value: string) => {
    w.page.drawText(label, { x: w.m + x, y: w.y - 9, size: 8.5, font, color: MUTED });
    w.page.drawText(value, { x: w.m + x, y: w.y - 27, size: 15, font: bold });
  };
  w.ensure(48);
  const col = w.w / 3;
  kpi(0, "Rent for the period", inr(m.totalRent));
  kpi(col, "Paid", inr(m.totalPaid));
  kpi(col * 2, "Balance due", inr(m.balance));
  w.gap(42);
  if (m.totalCharged !== m.totalRent)
    w.para(
      `Total billed ${inr(m.totalCharged)}, which includes meter bills and late fees on top of the rent. Rent for HRA is ${inr(m.totalRent)}.`,
      { size: 8.5, color: MUTED, after: 6 },
    );

  heading(w, "Month by month");
  const anyFees = m.months.some((x) => x.fees > 0);
  table(
    w,
    ["Month", "Rent", "Utilities", ...(anyFees ? ["Late fees"] : []), "Paid", "Balance"],
    m.months.map((x) => [monthLong(x.month), x.rent, x.utilities, ...(anyFees ? [x.fees] : []), x.paid, x.balance]),
    {
      numWidth: anyFees ? 66 : 76,
      total: [
        "Total",
        m.totalRent,
        m.months.reduce((s, x) => s + x.utilities, 0),
        ...(anyFees ? [m.months.reduce((s, x) => s + x.fees, 0)] : []),
        m.totalPaid,
        m.balance,
      ],
    },
  );

  heading(w, "Payments received", m.payments.length ? undefined : "No confirmed payments for this period yet.");
  if (m.payments.length)
    table(
      w,
      ["Paid on · for", "Method", "Reference", "Receipt", "Amount"],
      m.payments.map((p) => [
        `${dateLong(p.paidOn)} · ${monthsLabel(p.months)}`,
        METHOD[p.method] ?? p.method,
        p.utr || "-",
        p.receipt || "-",
        p.amount,
      ]),
      { numWidth: 70, total: ["Total received", "", "", "", m.payments.reduce((s, p) => s + p.amount, 0)] },
    );

  w.rule();
  w.para(
    `I, ${m.ownerName || "the landlord"}, confirm that I received the rent shown above from ${m.tenantName} for the premises at ${m.unitLabel}, ${m.propertyName}${m.address ? `, ${m.address}` : ""}.`,
    { size: 10, after: 26 },
  );
  w.text(m.ownerName || "Landlord", { bold: true });
  w.lineDone(10);
  w.text(`Landlord${m.ownerPhone ? ` · ${m.ownerPhone}` : ""}${m.ownerPan ? ` · PAN ${m.ownerPan}` : ""}`, {
    size: 8.5,
    color: MUTED,
  });
  w.lineDone(8.5);
  if (!m.ownerPan && m.totalRent > 100000)
    w.para(
      "Rent above Rs. 1,00,000 a year needs the landlord's PAN for an HRA claim. The landlord can add it in pOS Settings.",
      { size: 8.5, color: MUTED, after: 4 },
    );
  w.footer("Generated by pOS from the rent ledger. A computer-generated statement.");
  return doc.save();
}
